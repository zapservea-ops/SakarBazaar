export function resolveProviderSymbol(
  definition: InstrumentDefinition,
  providerId: string,
): string {
  return (
    definition.providerSymbols[providerId] ??
    definition.providerSymbols[definition.exchange.toLowerCase()] ??
    `${definition.exchange}:${definition.symbol}`
  );
}
